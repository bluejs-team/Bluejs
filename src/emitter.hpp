    void emitPendingFeBodies(std::ostringstream& out) {
        for (const ASTNode* p : fe_emit_order_) {
            auto it = fe_uid_by_node_.find(p);
            if (it == fe_uid_by_node_.end())
                continue;
            emitNativeFeFunction(*p, "__jsc_fe_" + std::to_string(it->second), out);
        }
        fe_emit_order_.clear();
        fe_uid_by_node_.clear();
        max_fe_uid_ = 0;
    }

    static bool functionAstHasBindingId(const ASTNode& node) {
        if (node.type == "FunctionDeclaration")
            return true;
        return node.type == "FunctionExpression" &&
               node.data.contains("id") && node.data["id"].is_object();
    }

    static void extractFunctionSignature(const ASTNode& node, std::string* nameOut,
                                         std::vector<std::string>* params,
                                         const ASTNode** bodyOut) {
        nameOut->clear();
        params->clear();
        *bodyOut = nullptr;
        size_t i = 0;
        if (functionAstHasBindingId(node)) {
            if (i < node.children.size() && node.children[i].type == "Identifier")
                *nameOut = identName(node.children[i]);
            ++i;
        }
        for (; i < node.children.size(); ++i) {
            const ASTNode& p = node.children[i];
            if (p.type == "BlockStatement") {
                *bodyOut = &p;
                break;
            }
            // AssignmentPattern: `x = default` → extract name from left
            if (p.type == "AssignmentPattern" && !p.children.empty())
                params->push_back(identName(p.children[0]));
            // RestElement: `...rest` → extract name from argument
            else if (p.type == "RestElement" && !p.children.empty())
                params->push_back(identName(p.children[0]));
            // ObjectPattern / ArrayPattern param: name stays <anon> (handled at runtime)
            else
                params->push_back(identName(p));
        }
        // For ArrowFunctionExpression the body may be a plain expression (not BlockStatement)
        if (!*bodyOut && node.type == "ArrowFunctionExpression") {
            for (; i < node.children.size(); ++i) {
                if (node.children[i].type != "Identifier")
                    *bodyOut = &node.children[i];
            }
        }
    }

    void emitNativeFeFunction(const ASTNode& feNode, const std::string& qname,
                              std::ostringstream& out) {
        (void)feNode;  // accessed via extractFunctionSignature
        std::string bindName;
        std::vector<std::string> params;
        const ASTNode* body = nullptr;
        extractFunctionSignature(feNode, &bindName, &params, &body);
        (void)bindName;

        // Find the raw param nodes (past the optional id node) so we can detect
        // RestElement / AssignmentPattern.
        size_t paramStart = functionAstHasBindingId(feNode) ? 1 : 0;
        // For ArrowFunctionExpression there's no id node.
        std::vector<const ASTNode*> rawParams;
        for (size_t i = paramStart; i < feNode.children.size(); ++i) {
            const ASTNode& p = feNode.children[i];
            if (p.type == "BlockStatement") break;
            // Arrow: body may be an expression node - stop at non-param types
            if (feNode.type == "ArrowFunctionExpression" &&
                p.type != "Identifier" && p.type != "AssignmentPattern" &&
                p.type != "RestElement" && p.type != "ObjectPattern" &&
                p.type != "ArrayPattern")
                break;
            rawParams.push_back(&p);
        }

        // ── Hoist nested FunctionDeclarations BEFORE the outer function header ─
        // (nested fn-defs are illegal in C++; emit them as preceding siblings)
        // Pre-add params to ownedLocals_ so free-var collection sees them.
        for (size_t i = 0; i < rawParams.size(); ++i) {
            const ASTNode& rp = *rawParams[i];
            std::string n;
            if (rp.type == "RestElement" && !rp.children.empty())       n = identName(rp.children[0]);
            else if (rp.type == "AssignmentPattern" && !rp.children.empty()) n = identName(rp.children[0]);
            else if (rp.type == "Identifier") n = identName(rp);
            if (!n.empty()) ownedLocals_.insert(n);
        }

        struct NestedFn { std::string jsName; std::string cName; };
        std::vector<NestedFn> nestedFns;
        if (body && body->type == "BlockStatement") {
            int nestIdx = 0;
            for (const auto& s : body->children) {
                if (s.type != "FunctionDeclaration" || s.children.empty()) continue;
                std::string innerJs = identName(s.children[0]);
                std::string innerC  = qname + "_nd" + std::to_string(nestIdx++)
                                    + "_" + sanitizeName(innerJs);

                // Collect free variables: identifiers in the nested FD body that
                // belong to the outer FE's scope but are not the nested FD's own params.
                std::set<std::string> innerParams;
                for (size_t pi = 0; pi < s.children.size(); ++pi) {
                    const ASTNode& p = s.children[pi];
                    if (p.type == "BlockStatement") break;
                    if (p.type == "Identifier") innerParams.insert(identName(p));
                    else if (p.type == "AssignmentPattern" && !p.children.empty())
                        innerParams.insert(identName(p.children[0]));
                    else if (p.type == "RestElement" && !p.children.empty())
                        innerParams.insert(identName(p.children[0]));
                }
                // Combine inner params + already-declared hoisted inner fns so far
                for (const auto& nf2 : nestedFns) innerParams.insert(nf2.jsName);

                std::vector<std::string> freeVars;
                std::set<std::string> seen;
                for (size_t ci = 0; ci < s.children.size(); ++ci) {
                    if (s.children[ci].type == "BlockStatement") {
                        collectFreeVars(s.children[ci], innerParams, ownedLocals_,
                                        freeVars, seen);
                        break;
                    }
                }
                if (!freeVars.empty())
                    nestedFdCaptures_[innerC] = freeVars;

                emitNativeFeFunction(s, innerC, out); // emitted before outer header
                nestedFns.push_back({innerJs, innerC});
            }
        }

        out << "static JsValue " << qname << "(int argc, JsValue* argv) {\n";
        if (params.empty())
            out << "    (void)argc;\n"
                   "    (void)argv;\n";

        std::set<std::string> outerOwned = std::move(ownedLocals_);
        ownedLocals_.clear();

        for (size_t i = 0; i < rawParams.size(); ++i) {
            const ASTNode& rp = *rawParams[i];
            if (rp.type == "RestElement" && !rp.children.empty()) {
                // ...rest → collect remaining argv into an array object
                std::string rname = identName(rp.children[0]);
                out << "    JsOwned " << rname << " = JsOwned::from_value(js_obj_new());\n"
                    << "    { int __ri = 0; char __rk[24];\n"
                    << "      for (int __rj = " << i << "; __rj < argc; ++__rj) {\n"
                    << "        snprintf(__rk, 24, \"%d\", __ri++);\n"
                    << "        js_obj_set(" << rname << ".ptr(), __rk, js_clone_value(argv[__rj])); }\n"
                    << "      snprintf(__rk, 24, \"%d\", __ri);\n"
                    << "      js_obj_set(" << rname << ".ptr(), \"length\", JS_NUM(__ri)); }\n";
                ownedLocals_.insert(rname);
                break; // rest must be last
            }
            std::string pname = params[i];
            if (rp.type == "AssignmentPattern" && rp.children.size() >= 2) {
                // default param: use argv[i] unless undefined
                out << "    JsOwned " << pname << " = (argc > " << i
                    << " && argv[" << i << "].tag != JS_UNDEFINED) "
                    << "? JsOwned::from_value(js_clone_value(argv[" << i << "])) : "
                    << "JsOwned::from_value(";
                emitOwned(rp.children[1], out);
                out << ");\n";
            } else {
                out << "    JsOwned " << pname << " = argc > " << i
                    << " ? JsOwned::from_value(js_clone_value(argv[" << i << "])) : "
                       "JsOwned();\n";
            }
            ownedLocals_.insert(pname);
        }

        int oldNr = native_return_mode_;
        native_return_mode_ = 1;

        // Declare 'arguments' array so Babel helpers that reference it work
        out << "    JsOwned arguments = JsOwned::from_value(js_obj_new());\n"
               "    { char __ak[24]; for (int __ai = 0; __ai < argc; ++__ai) {\n"
               "        snprintf(__ak, 24, \"%d\", __ai);\n"
               "        js_obj_set(arguments.ptr(), __ak, js_clone_value(argv[__ai])); }\n"
               "      js_obj_set(arguments.ptr(), \"length\", JS_NUM((double)argc)); }\n";
        ownedLocals_.insert("arguments");

        // Emit closure captures and declare hoisted inner functions as JsOwned locals
        for (const auto& nf : nestedFns) {
            // Store captured outer-scope variables into the closure store
            auto capIt = nestedFdCaptures_.find(nf.cName);
            if (capIt != nestedFdCaptures_.end() && !capIt->second.empty()) {
                int nc = (int)capIt->second.size();
                out << "    { JsValue __caps[] = {";
                for (int ci = 0; ci < nc; ++ci) {
                    if (ci) out << ", ";
                    std::string cn = sanitizeName(capIt->second[(size_t)ci]);
                    if (isOwnedBinding(capIt->second[(size_t)ci]))
                        out << cn << ".borrow()";
                    else
                        out << resolve(capIt->second[(size_t)ci]);
                }
                out << "};\n      js_closure_set(" << nf.cName << ", " << nc
                    << ", __caps); }\n";
            }
            out << "    JsOwned " << sanitizeName(nf.jsName)
                << " = JsOwned::from_value(js_native_fn(" << nf.cName << "));\n";
            ownedLocals_.insert(nf.jsName);
        }

        // Inject reads for any captured variables this function itself needs
        {
            auto capIt = nestedFdCaptures_.find(qname);
            if (capIt != nestedFdCaptures_.end()) {
                for (int ci = 0; ci < (int)capIt->second.size(); ++ci) {
                    const std::string& capJsName = capIt->second[(size_t)ci];
                    std::string capCName = sanitizeName(capJsName);
                    out << "    JsOwned " << capCName
                        << " = JsOwned::from_value(js_closure_get("
                        << qname << ", " << ci << "));\n";
                    ownedLocals_.insert(capJsName);
                }
            }
        }

        if (body) {
            if (body->type == "BlockStatement") {
                for (const auto& s : body->children) {
                    if (s.type == "FunctionDeclaration") continue; // already hoisted
                    emitStmt(s, out, 1);
                }
            } else {
                // Arrow expression body: `x => x + 1` → return x + 1
                out << "    return js_clone_value(";
                emitValue(*body, out);
                out << ");\n";
            }
        }
        native_return_mode_ = oldNr;
        ownedLocals_ = std::move(outerOwned);

        bool endsRet = body && body->type == "BlockStatement" &&
                       !body->children.empty() &&
                       body->children.back().type == "ReturnStatement";
        if (!endsRet && !(body && body->type != "BlockStatement"))
            out << "    return js_clone_value(JS_UNDEFINED());\n";
        out << "}\n\n";
    }

